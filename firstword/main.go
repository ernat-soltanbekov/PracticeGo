package main

import "fmt"

func FirstWord(s string) string { // Функция получает строку и возвращает первое слово из неё.
	word := ""               // Здесь будем постепенно собирать символы первого слова.
	inWord := false          // Флаг показывает, начали ли мы уже читать слово.
	for _, char := range s { // Проходим по каждому символу входной строки слева направо.
		if char != ' ' { // Если текущий символ не является пробелом...
			inWord = true        // ...значит, мы вошли внутрь слова.
			word += string(char) // Добавляем текущий символ к нашему слову.
		}
		if char == ' ' { // Если встретили пробел...
			if inWord == true { // ...и до этого уже начали читать слово...
				break // ...значит, первое слово закончилось, поэтому прекращаем цикл.
			}
		}
	}
	return word + "\n" // Возвращаем найденное первое слово и добавляем перевод строки.
}

func main() { // Точка входа в программу.
	fmt.Print(FirstWord("hello there"))            // Передаём строку и выводим найденное первое слово.
	fmt.Print(FirstWord(""))                       // Передаём пустую строку и выводим результат.
	fmt.Print(FirstWord("hello   .........  bye")) // Проверяем, что после первого слова функция останавливается на пробеле.
}
