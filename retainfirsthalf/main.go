package main // Подключаем главный пакет программы — именно с него начинается выполнение.

import "fmt" // Подключаем пакет fmt для вывода результатов в консоль.

func RetainFirstHalf(str string) string { // Функция получает строку и должна вернуть её первую половину.
	if len(str)%2 == 0 { // Проверяем, является ли длина строки чётной.
		return str[:len(str)/2] // Если длина чётная, берём ровно половину строки.
	}
	return str[:len(str)/2+1] // Если длина нечётная, берём первую половину вместе с центральным символом.
}

func main() { // Главная функция программы.
	fmt.Println(RetainFirstHalf("This is the 1st halfThis is the 2nd half")) // Передаём длинную строку и выводим её первую половину.
	fmt.Println(RetainFirstHalf("A"))                                        // Проверяем работу функции со строкой из одного символа.
	fmt.Println(RetainFirstHalf(""))                                         // Проверяем работу функции с пустой строкой.
	fmt.Println(RetainFirstHalf("Hello World"))                              // Проверяем работу функции со строкой чётной длины.
}
