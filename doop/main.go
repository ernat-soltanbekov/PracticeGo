package main

import (
	"os" // Подключаем пакет os, чтобы получить аргументы, переданные программе из командной строки.
)

func main() { // Точка входа программы. Здесь начинается выполнение калькулятора.
	if len(os.Args) != 4 { // Проверяем, что пользователь передал ровно три аргумента: первое число, оператор и второе число.
		return // Если количество аргументов неправильное, прекращаем выполнение программы.
	}
	strVal1 := os.Args[1]      // Забираем первый аргумент командной строки — первое число в виде строки.
	operator := os.Args[2]     // Забираем второй аргумент — оператор математического действия.
	strVal2 := os.Args[3]      // Забираем третий аргумент — второе число в виде строки.
	val1, ok1 := Atoi(strVal1) // Преобразуем первое число из строки в int и одновременно получаем признак успешного преобразования.
	val2, ok2 := Atoi(strVal2) // Преобразуем второе число из строки в int и проверяем, получилось ли это сделать.
	if !ok1 || !ok2 {          // Если хотя бы одно из двух преобразований завершилось неудачно, дальше выполнять вычисления нельзя.
		return // Прекращаем выполнение программы, потому что входные данные некорректны.
	}
	switch operator { // Выбираем математическую операцию в зависимости от переданного пользователем оператора.
	case "+": // Если пользователь указал плюс, выполняем сложение двух чисел.
		res := val1 + val2                                        // Складываем первое и второе число и сохраняем результат.
		if (val2 > 0 && res < val1) || (val2 < 0 && res > val1) { // Проверяем переполнение при сложении: результат не должен неожиданно стать меньше или больше исходного числа.
			return // Если произошло переполнение, прекращаем выполнение без вывода неправильного результата.
		}
		println(res) // Выводим результат сложения.
	case "-": // Если пользователь указал минус, выполняем вычитание.
		res := val1 - val2                                        // Вычитаем второе число из первого и сохраняем результат.
		if (val2 > 0 && res > val1) || (val2 < 0 && res < val1) { // Проверяем, не произошло ли переполнение при вычитании.
			return // Если результат вышел за допустимый диапазон, прекращаем выполнение.
		}
		println(res) // Выводим результат вычитания.
	case "*": // Если пользователь указал звёздочку, выполняем умножение.
		res := val1 * val2                 // Умножаем первое число на второе.
		if val1 != 0 && res/val1 != val2 { // Если первое число не равно нулю, проверяем результат обратным делением и обнаруживаем возможное переполнение.
			return // При обнаружении переполнения прекращаем выполнение.
		}
		println(res) // Выводим результат умножения.
	case "/": // Если пользователь указал слэш, выполняем целочисленное деление.
		if val2 == 0 { // Перед делением обязательно проверяем, не равен ли делитель нулю.
			println("No division by 0") // Сообщаем пользователю, что деление на ноль невозможно.
			return                      // После сообщения прекращаем выполнение операции.
		}
		println(val1 / val2) // Делим первое число на второе и выводим целочисленный результат.
	case "%": // Если пользователь указал процент, вычисляем остаток от деления.
		if val2 == 0 { // Перед вычислением остатка также проверяем делитель на ноль.
			println("No modulo by 0") // Сообщаем пользователю, что получить остаток от деления на ноль невозможно.
			return                    // Прекращаем выполнение после обнаружения ошибки.
		}
		println(val1 % val2) // Вычисляем остаток от деления первого числа на второе и выводим его.
	default: // Если оператор не совпал ни с одним разрешённым вариантом, считаем ввод некорректным.
		return // Ничего не вычисляем и завершаем программу.
	}
}

func Atoi(s string) (int, bool) { // Функция получает строку и пытается превратить её в целое число. Второе значение bool сообщает, успешно ли это получилось.
	if s == "" { // Сначала проверяем, не пришла ли пустая строка. Преобразовывать здесь нечего.
		return 0, false // Возвращаем 0 и false: число не удалось получить.
	}
	sign := 1        // По умолчанию считаем число положительным.
	i := 0           // Индекс i показывает, с какого символа строки начинаем обработку.
	if s[0] == '-' { // Если первый символ — минус, число будет отрицательным.
		sign = -1 // Запоминаем отрицательный знак.
		i = 1     // Пропускаем символ '-' и начинаем читать цифры со следующей позиции.
	} else if s[0] == '+' { // Если первый символ — плюс, число остаётся положительным.
		i = 1 // Пропускаем символ '+' и начинаем читать цифры со следующей позиции.
	}
	if i == len(s) { // Если после знака больше ничего нет, например "+" или "-", это некорректное число.
		return 0, false // Возвращаем неуспешный результат.
	}
	res := 0                // Здесь будем постепенно собирать итоговое число из отдельных цифр.
	for ; i < len(s); i++ { // Идём по строке от текущего индекса до последнего символа.
		if s[i] < '0' || s[i] > '9' { // Проверяем, является ли текущий символ настоящей цифрой от 0 до 9.
			return 0, false // Если встретили что-то другое, строка не является корректным числом.
		}
		digit := int(s[i] - '0')                                                                                                                                  // Превращаем символ цифры, например '7', в обычное целое число 7.
		if res > 9223372036854775807 || (res == 9223372036854775807/10 && digit > 7 && sign == 1) || (res == 9223372036854775807/10 && digit > 8 && sign == -1) { // Проверяем, не выйдем ли мы за допустимый предел целого числа при добавлении очередной цифры.
			return 0, false // Если число слишком большое, прекращаем работу и сообщаем об ошибке.
		}
		res = res*10 + digit // Сдвигаем уже собранное число на один разряд влево и добавляем новую цифру.
	}
	return res * sign, true // Возвращаем готовое число с учётом знака и true, потому что преобразование прошло успешно.
}
